"""billing_closes: a finished month can be closed, so its billed figures stop moving

Revision ID: 0012
Revises: 0011

Until now every month was recomputed from today's tree, mappings and tariffs, so moving an asset, mapping or unmapping a point,
editing a rate or deleting an asset or a source changed past figures. An administrator can now CLOSE a finished month: the
exact output of month_costs() is stored in `billing_closes.figures` (JSONB), with the totals the list header and the audit
need (`total_kwh`, `total_cost`), the time zone and the currency it was computed in, and who closed it and when. REOPENING
keeps the row and sets the reopened trio (`reopened_at`, `reopened_name`, `reopen_note`, with `reopened_by` while the account
exists); a month is closed again by inserting a NEW row. At most one row per month is open (reopened_at IS NULL), which the
partial unique index `billing_closes_open_uq` enforces, so two simultaneous closes give one row.

`month` is TEXT 'YYYY-MM' (the API's own month format), not a date, so no time-zone conversion can slip in. `closed_by` and
`reopened_by` have the type of users.id (INTEGER) and are set to NULL when the account is deleted; `closed_name` keeps the
name that was shown.

Up, in one transaction: creates the table and its two indexes (the partial unique one and a plain one on (month, id)). No
other table is touched, no row is written and no role is given the new permission billing.close (nothing changes on
upgrade: the built-in Admin holds it from the code, any other role gets it when an administrator ticks it).

Down, in one transaction: drops the table. The closed months are lost, and nothing else is: no other table has a column or a
row that depends on it, so billing goes back to recomputing every month live. Upgrading again creates an empty table.

Nothing is imported from dcdash: a migration is frozen history.
"""
from alembic import op

revision = "0012"
down_revision = "0011"

UP = [
    """
    CREATE TABLE billing_closes (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        month TEXT NOT NULL CHECK (month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
        closed_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
        closed_name TEXT NOT NULL CHECK (btrim(closed_name) <> ''),
        closed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        note TEXT NOT NULL DEFAULT '',
        timezone TEXT NOT NULL,
        currency TEXT,
        total_kwh DOUBLE PRECISION NOT NULL,
        total_cost DOUBLE PRECISION,
        figures JSONB NOT NULL CHECK (jsonb_typeof(figures) = 'object'),
        reopened_at TIMESTAMPTZ,
        reopened_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
        reopened_name TEXT,
        reopen_note TEXT,
        CHECK ((reopened_at IS NULL) = (reopened_name IS NULL) AND (reopened_at IS NULL) = (reopen_note IS NULL))
    )
    """,
    "CREATE UNIQUE INDEX billing_closes_open_uq ON billing_closes (month) WHERE reopened_at IS NULL",
    "CREATE INDEX billing_closes_month_ix ON billing_closes (month, id)",
]

DOWN = [
    "DROP TABLE IF EXISTS billing_closes",
]


def upgrade() -> None:
    for statement in UP:
        op.execute(statement)


def downgrade() -> None:
    for statement in DOWN:
        op.execute(statement)
