"""the asset kinds registry: asset_kinds, seeded from the kinds assets already use

Revision ID: 0010
Revises: 0009

An administrator says once what each kind of asset looks like: a row of `asset_kinds` holds a kind's name and the icon its
assets show unless they have an icon of their own (`assets.icon`). `assets.kind` stays free text with no foreign key; an asset
belongs to a registry row when the normalised kind text (the `key`, see kind_key below) equals the row's key, so "Rack" and
" rack " are one kind. `icon` is an id of backend/dcdash/core/asset_icons.py, checked by the API, not by the database.

Up, in one transaction: creates the table with a UNIQUE index on `key`, then seeds it so that every existing asset keeps the
icon it shows today (its own icon, else the keyword guess on its kind text). A key is registered when every spelling of it in
`assets.kind` is at most 200 UTF-16 code units (the guess reads no further) and the guess gives ALL its spellings the same
icon; the row is named after the most used spelling (ties: the spelling that sorts first by code point), tidied the way the
front end's cleanKind does, and takes that icon. A key that cannot be registered without changing some asset's icon ("LVPanel"
guesses panel and "lvpanel" guesses generic; a blank kind; an over-long kind) gets no row and stays with the keyword guess until
an administrator registers it. Then the starter kinds (Site, Building, Room, Row, Rack, Panel, Meter, Circuit, Other equipment
and generic) are added for every key no asset uses. Rows are inserted in key order, so the ids are the same on every run. No
other table is touched and no value of `assets` changes.

Down, in one transaction: drops the table. Only the registry is lost; icons go back to the keyword guess, which is what every
version before 0010 did. `upgrade` afterwards seeds the registry again from the assets as they are then.

The seed needs the keyword guess of frontend/src/lib/kindIcon.ts and the key rule of frontend/src/lib/kinds.ts; this file holds
frozen Python copies of both (a migration imports nothing from dcdash). backend/tests/test_asset_kinds_parity.py holds them to
the answers of tests/fixtures/kind_samples.json, which frontend/src/lib/kindSamples.test.ts holds the TypeScript to. A later
change to kindIcon.ts updates those tests, never this file.
"""
import re
import unicodedata

import sqlalchemy as sa
from alembic import op

revision = "0010"
down_revision = "0009"

UP = [
    """
    CREATE TABLE asset_kinds (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL CHECK (btrim(name) <> ''),
        key TEXT NOT NULL CHECK (key <> ''),
        icon TEXT NOT NULL DEFAULT 'generic',
        created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    )
    """,
    "CREATE UNIQUE INDEX asset_kinds_key_uq ON asset_kinds (key)",
]

DOWN = [
    "DROP TABLE IF EXISTS asset_kinds",
]

STARTERS = ("Site", "Building", "Room", "Row", "Rack", "Panel", "Meter", "Circuit", "Other equipment", "generic")

# ---- frozen copy of frontend/src/lib/kinds.ts (kindKey, cleanKind) ---------------------------------------------------------

# ECMAScript white space, spelled out (what JavaScript's trim() and \s remove; Python's str.split() differs).
BLANKS = re.compile(r"[\t\n\v\f\r \u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000\ufeff]+")


def kind_key(text: str) -> str:
    return BLANKS.sub(" ", unicodedata.normalize("NFC", text)).strip(" ").lower()


def clean_kind(text: str) -> str:
    # No Unicode normalisation here, as in the front end's cleanKind.
    return BLANKS.sub(" ", text).strip(" ")


# ---- frozen copy of frontend/src/lib/kindIcon.ts ---------------------------------------------------------------------------

# Walked top to bottom, the first row with a matching word wins. The ids are asset icon ids (kindUps is "ups").
TABLE = (
    ("ups", {"ups", "rectifier", "inverter"}),
    ("battery", {"battery", "batteries", "bess"}),
    ("pdu", {"pdu", "rpp", "rpdu", "strip"}),
    ("generator", {"generator", "genset", "gen"}),
    ("transformer", {"transformer", "trafo", "xfmr", "substation"}),
    ("chiller", {"chiller"}),
    ("crac", {"crac", "crah", "ahu"}),
    ("fan", {"fan"}),
    ("circuit", {"circuit", "breaker", "feeder", "ats", "sts", "busway", "busbar", "mcb", "mccb", "transferswitch"}),
    ("panel", {"panel", "panelboard", "switchboard", "switchgear", "mdb"}),
    ("pump", {"pump"}),
    ("crac", {"cooling", "cooler"}),
    ("meter", {"meter", "submeter", "metering"}),
    ("sensor", {"sensor"}),
    ("rack", {"rack", "cabinet", "enclosure"}),
    ("row", {"row", "aisle", "pod"}),
    ("room", {"room", "hall", "suite", "floor", "cage", "zone"}),
    ("building", {"building", "block", "tower", "plant"}),
    ("site", {"site", "dc", "datacenter", "datacentre", "campus", "facility"}),
    ("panel", {"lv", "mv", "hv", "db", "distribution"}),
)

MAX_KIND_UNITS = 200  # the matcher's own clamp, in UTF-16 code units: JavaScript's kind.slice(0, 200)


def utf16_units(text: str) -> int:
    return len(text.encode("utf-16-le", "surrogatepass")) // 2


def clamp(text: str) -> str:
    # A cut in the middle of a surrogate pair leaves a lone surrogate, as in JavaScript.
    return text.encode("utf-16-le", "surrogatepass")[: 2 * MAX_KIND_UNITS].decode("utf-16-le", "surrogatepass")


def words(kind: str) -> list[str]:
    # [0-9], never \d: Python's \d matches every Unicode digit, JavaScript's only 0-9 ("UPS" plus U+0663 must stay generic).
    spaced = clamp(kind)
    spaced = re.sub(r"([a-z])([A-Z])", r"\1 \2", spaced)
    spaced = re.sub(r"([A-Z]+)([A-Z](?!s(?![a-z]))[a-z])", r"\1 \2", spaced)
    spaced = re.sub(r"([A-Za-z])([0-9])", r"\1 \2", spaced)
    spaced = re.sub(r"([0-9])([A-Za-z])", r"\1 \2", spaced)
    # [\W_] is exactly [^\p{L}\p{N}] (compared over every code point).
    tokens = [token for token in re.split(r"[\W_]+", unicodedata.normalize("NFC", spaced).lower()) if token]
    joined: list[str] = []
    for token in tokens:
        last = joined[-1] if joined else None
        if last == "data" and re.fullmatch(r"cent(?:er|re)s?", token):
            joined[-1] = f"data{token}"
        elif last == "distribution" and re.fullmatch(r"units?", token):
            joined[-1] = "pdu"
        elif last == "transfer" and re.fullmatch(r"switch(?:es)?", token):
            joined[-1] = "transferswitch"
        else:
            joined.append(token)
    return joined


def suggest_icon(kind: str) -> str:
    """The asset icon id the keyword guess gives a kind text: 'generic' when no word is recognised."""
    tokens = [variant for token in words(kind) for variant in ((token, token[:-1]) if token.endswith("s") else (token,))]
    for icon, known in TABLE:
        if any(token in known for token in tokens):
            return icon
    return "generic"


# ---- the seed ----------------------------------------------------------------------------------------------------------------

def seed_rows(counts: dict[str, int]) -> list[tuple[str, str, str]]:
    """The (key, name, icon) rows to insert, in key order, for `counts` = how many assets carry each distinct kind text."""
    spellings: dict[str, dict[str, int]] = {}
    for kind, n in counts.items():
        key = kind_key(kind)
        if key:
            spellings.setdefault(key, {})[kind] = n
    rows: dict[str, tuple[str, str]] = {}
    for key, found in spellings.items():
        if any(utf16_units(spelling) > MAX_KIND_UNITS for spelling in found):
            continue
        if len({suggest_icon(spelling) for spelling in found}) != 1:
            continue
        best = sorted(found, key=lambda spelling: (-found[spelling], spelling))[0]  # code-point order, never the collation
        rows[key] = (clean_kind(best), suggest_icon(best))
    for name in STARTERS:
        key = kind_key(name)
        if key not in spellings:  # a key assets use is theirs, registered or not
            rows[key] = (name, suggest_icon(name))
    return [(key, name, icon) for key, (name, icon) in sorted(rows.items())]


def upgrade() -> None:
    for statement in UP:
        op.execute(statement)
    bind = op.get_bind()
    counts = {kind: n for kind, n in bind.execute(sa.text("SELECT kind, count(*) FROM assets GROUP BY kind"))}
    for key, name, icon in seed_rows(counts):
        bind.execute(
            sa.text("INSERT INTO asset_kinds (name, key, icon) VALUES (:name, :key, :icon)"),
            {"name": name, "key": key, "icon": icon},
        )


def downgrade() -> None:
    for statement in DOWN:
        op.execute(statement)
