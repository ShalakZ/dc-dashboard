"""roles and permissions: the roles table, users.role_id in place of users.role

Revision ID: 0009
Revises: 0008

An account used to carry one of three role names in `users.role` (a CHECK allowed only admin, operator, viewer). From now on
it points at a row of a new `roles` table with `users.role_id`, and what a role may do is a list of permission ids (the
catalogue is backend/dcdash/core/permissions.py; the API ignores any id in a stored list that the catalogue does not know).

Up, in one transaction: creates `roles` (names are unique ignoring case; the permission list must be a JSON array) and seeds
the three built-in roles with ids 1, 2 and 3, which stay what they were: viewer, operator and admin. The permission lists of
the seed are only a mirror for people who read the database; the built-in roles get their permissions from the code, never
from these rows. Then adds `users.role_id` (a foreign key, ON DELETE RESTRICT: a role that an account holds cannot be
deleted), fills it from `users.role` (an impossible value, which the old CHECK did not allow, becomes Viewer: least
privilege), makes it NOT NULL, indexes it and drops `users.role` with its CHECK. No other table is touched; every account
keeps its id, name, password hash, sessions, preferences and audit trail.

Down, in one transaction: puts `users.role` back as the LAST column of `users` (the same TEXT NOT NULL with the same CHECK,
`users_role_check`), filled by role id (1 viewer, 2 operator, 3 admin), drops `users.role_id` and drops `roles`. The only
lossy case is a custom role: its accounts become `viewer` on the way down, and the custom roles themselves are gone.
`upgrade` afterwards seeds the three built-in roles again and gives every account the id of its name.
"""
import json

from alembic import op

revision = "0009"
down_revision = "0008"

# Literals on purpose: a migration is frozen history and imports nothing from dcdash. The ids are the 0009 catalogue, in
# the catalogue's order; backend/tests/test_schema_roles.py pins these rows to the code's built-in sets.
VIEWER = ["assets.view", "dashboards.view", "billing.view", "billing.export"]
OPERATOR = [
    "assets.view", "dashboards.view", "dashboards.edit", "billing.view", "billing.export", "tariffs.view",
    "sources.view", "sources.test", "discovery.view", "diagnostics.run",
]
ADMIN = [
    "assets.view", "assets.edit", "assets.delete", "dashboards.view", "dashboards.edit", "dashboards.default",
    "billing.view", "billing.export", "tariffs.view", "tariffs.edit", "sources.view", "sources.edit", "sources.test",
    "discovery.view", "discovery.edit", "discovery.scan", "discovery.accept", "storage.view", "storage.edit",
    "settings.view", "settings.edit", "audit.view", "audit.export", "users.view", "users.edit", "roles.manage",
    "diagnostics.view", "diagnostics.run",
]


def seed(role_id: int, name: str, description: str, permissions: list[str]) -> str:
    return (
        "INSERT INTO roles (id, name, description, builtin, permissions) "
        f"VALUES ({role_id}, '{name}', '{description}', true, '{json.dumps(permissions)}'::jsonb)"
    )


UP = [
    """
    CREATE TABLE roles (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL CHECK (btrim(name) <> ''),
        description TEXT NOT NULL DEFAULT '',
        builtin BOOLEAN NOT NULL DEFAULT false,
        permissions JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(permissions) = 'array'),
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    )
    """,
    "CREATE UNIQUE INDEX roles_name_lower ON roles (lower(name))",
    seed(1, "viewer", "Sees assets, dashboards and billing.", VIEWER),
    seed(2, "operator", "Also edits dashboards, tests sources and sees scans.", OPERATOR),
    seed(3, "admin", "Everything, including users and roles.", ADMIN),
    "SELECT setval(pg_get_serial_sequence('roles', 'id'), 3)",
    "ALTER TABLE users ADD COLUMN role_id BIGINT REFERENCES roles(id) ON DELETE RESTRICT",
    "UPDATE users SET role_id = COALESCE((SELECT id FROM roles WHERE name = users.role), 1)",
    "ALTER TABLE users ALTER COLUMN role_id SET NOT NULL",
    "CREATE INDEX users_role_id ON users (role_id)",
    "ALTER TABLE users DROP COLUMN role",
]

DOWN = [
    "ALTER TABLE users ADD COLUMN role TEXT",
    "UPDATE users SET role = CASE role_id WHEN 1 THEN 'viewer' WHEN 2 THEN 'operator' WHEN 3 THEN 'admin' ELSE 'viewer' END",
    "ALTER TABLE users ALTER COLUMN role SET NOT NULL",
    "ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN ('admin', 'operator', 'viewer'))",
    "DROP INDEX IF EXISTS users_role_id",
    "ALTER TABLE users DROP COLUMN IF EXISTS role_id",
    "DROP TABLE IF EXISTS roles",
]


def upgrade() -> None:
    for statement in UP:
        op.execute(statement)


def downgrade() -> None:
    for statement in DOWN:
        op.execute(statement)
